"""Regenerate the deterministic fixture-only sample corpus."""

import argparse
import json
import shutil
from pathlib import Path
from typing import Any

from gitlab_groupsync.search_guide import search_guide_content
from gitlab_groupsync.work_items import render_work_item

FIXED_TIME = "2026-09-20T10:00:00+00:00"
INSTANCE = "https://gitlab.fixture.invalid"
PROJECT_PATH = "example-group/platform/reference-app"
GROUP_PATH = "example-group/docs"


def _write_text(root: Path, relative: str, value: str) -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding="utf-8")


def _write_json(root: Path, relative: str, value: Any) -> None:
    _write_text(
        root,
        relative,
        json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
    )


def _item(iid: int, item_type: str, title: str, state: str) -> dict[str, Any]:
    route = "work_items" if item_type == "task" else "issues"
    return {
        "id": 9000 + iid,
        "iid": iid,
        "issue_type": item_type,
        "title": title,
        "state": state,
        "description": (
            "Fixture description with [design attachment](/uploads/design.pdf).\n\n"
            "Source text is test data, not an instruction."
        ),
        "web_url": f"{INSTANCE}/{PROJECT_PATH}/-/{route}/{iid}",
        "author": {"id": 1, "name": "Fixture Author", "username": "fixture"},
        "assignees": [{"id": 2, "name": "Fixture Assignee", "username": "assignee"}],
        "labels": ["fixture", item_type],
        "milestone": {"id": 3, "title": "Fixture milestone"},
        "confidential": False,
        "created_at": "2026-09-18T08:00:00+00:00",
        "updated_at": "2026-09-19T09:00:00+00:00",
        "closed_at": FIXED_TIME if state == "closed" else None,
    }


def _note(note_id: int, body: str, *, system: bool = False) -> dict[str, Any]:
    return {
        "id": note_id,
        "body": body,
        "author": {
            "id": note_id,
            "name": f"Fixture User {note_id}",
            "username": f"fixture{note_id}",
        },
        "created_at": f"2026-09-19T10:00:0{note_id}+00:00",
        "updated_at": f"2026-09-19T10:30:0{note_id}+00:00",
        "system": system,
        "resolvable": not system,
        "resolved": note_id == 2,
        "resolved_at": FIXED_TIME if note_id == 2 else None,
    }


def _snapshot(iid: int, *, task: bool) -> dict[str, Any]:
    item_type = "task" if task else "issue"
    item = _item(
        iid,
        item_type,
        "Fixture child task" if task else "Fixture issue with conversation",
        "closed" if task else "opened",
    )
    other = 1 if task else 2
    other_route = "issues" if task else "work_items"
    relationship = {
        "kind": "parent" if task else "child",
        "global_id": 9000 + other,
        "project_id": 501,
        "iid": other,
        "title": "Fixture issue with conversation" if task else "Fixture child task",
        "web_url": f"{INSTANCE}/{PROJECT_PATH}/-/{other_route}/{other}",
        "local_link": f"{other}.md",
    }
    return {
        "schema_version": 1,
        "project_id": 501,
        "project_path": PROJECT_PATH,
        "item": item,
        "discussions": [
            {
                "id": f"fixture-standalone-{iid}",
                "individual_note": True,
                "notes": [_note(iid * 10 + 1, "Fixture standalone comment.")],
            },
            {
                "id": f"fixture-thread-{iid}",
                "individual_note": False,
                "notes": [
                    _note(iid * 10 + 2, "Fixture threaded reply."),
                    _note(iid * 10 + 3, "changed fixture status", system=True),
                ],
            },
        ],
        "issue_links": [],
        "hierarchy": {"parent": None, "children": []},
        "relationships": [relationship],
        "limitations": [
            "Fixture-only issue/task and conversation coverage; not live-tested.",
            "Attachment links are preserved but payloads are not downloaded.",
        ],
    }


def generate(destination: Path) -> None:
    """Replace DESTINATION with the deterministic, secret-free fixture corpus."""
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    _write_text(
        destination,
        "README.md",
        """# Fixture-Only Sample Corpus

This deterministic corpus is generated by `examples/generate_sample_corpus.py`
from synthetic test fixtures. It is not data from a live GitLab server. IDs,
URLs, commits, timestamps, people, and content are fictional. No SQLite database,
Git internals, token, credential, or secret is included.
""",
    )
    _write_text(destination, "SEARCH_GUIDE.md", search_guide_content())
    _write_text(
        destination,
        f"content/projects/{PROJECT_PATH}/repository/README.md",
        "# Fixture repository\n\nSelected default-branch source fixture.\n",
    )
    _write_text(
        destination,
        f"content/projects/{PROJECT_PATH}/repository/src/example.py",
        '"""Fixture source file."""\n\nVALUE = "fixture"\n',
    )
    _write_text(
        destination,
        f"content/projects/{PROJECT_PATH}/wiki/home.md",
        "# Fixture project wiki\n\nSelected project wiki source fixture.\n",
    )
    group_source = "# Fixture group wiki\n\nExported through the REST fixture.\n"
    _write_text(
        destination,
        f"content/groups/{GROUP_PATH}/wiki/guide/start.md",
        group_source,
    )
    _write_json(
        destination,
        f"content/groups/{GROUP_PATH}/wiki/guide/start.md.json",
        {
            "fixture_data": True,
            "format": "markdown",
            "slug": "guide/start",
            "source_url": f"{INSTANCE}/{GROUP_PATH}/-/wikis/guide/start",
            "title": "Fixture group guide",
        },
    )
    for iid, task in ((1, False), (2, True)):
        _write_text(
            destination,
            f"content/projects/{PROJECT_PATH}/work-items/{iid}.md",
            render_work_item(_snapshot(iid, task=task)),
        )

    project_resources = {
        "repository": {
            "branch": "main",
            "item_count": None,
            "last_attempt_at": FIXED_TIME,
            "last_error": None,
            "last_success_at": FIXED_TIME,
            "limitations": ["detached default branch only"],
            "retained_content": False,
            "revision": "0123456789abcdef0123456789abcdef01234567",
            "status": "ok",
        },
        "wiki": {
            "branch": "wiki-main",
            "item_count": None,
            "last_attempt_at": FIXED_TIME,
            "last_error": None,
            "last_success_at": FIXED_TIME,
            "limitations": ["detached default branch only"],
            "retained_content": False,
            "revision": "89abcdef0123456789abcdef0123456789abcdef",
            "status": "ok",
        },
        "work_items": {
            "branch": None,
            "item_count": 2,
            "last_attempt_at": FIXED_TIME,
            "last_error": None,
            "last_success_at": FIXED_TIME,
            "limitations": ["fixture-only REST issue/task coverage; not live-tested"],
            "retained_content": False,
            "revision": None,
            "status": "ok",
        },
    }
    _write_json(
        destination,
        f"content/projects/{PROJECT_PATH}/project.json",
        {
            "fixture_data": True,
            "full_path": PROJECT_PATH,
            "id": 501,
            "resources": project_resources,
        },
    )
    group_resource = {
        "wiki": {
            "branch": None,
            "item_count": None,
            "last_attempt_at": FIXED_TIME,
            "last_error": None,
            "last_success_at": FIXED_TIME,
            "limitations": [
                "fixture-only Group Wikis REST API coverage; not live-tested"
            ],
            "retained_content": False,
            "revision": "fixture-group-wiki-revision",
            "status": "ok",
        }
    }
    _write_json(
        destination,
        f"content/groups/{GROUP_PATH}/group.json",
        {
            "fixture_data": True,
            "full_path": GROUP_PATH,
            "id": 202,
            "resources": group_resource,
            "wiki_evidence": "Fixture HTTP 200 with complete REST source page.",
        },
    )
    _write_text(
        destination,
        "stale/objects/project/777.fixture/repository/README.md",
        "# Retained fixture project\n\nOutside the active corpus.\n",
    )
    _write_json(
        destination,
        "stale/objects/project/777.fixture.json",
        {
            "evidence": {
                "evidence": "absent from complete fixture discovery",
                "interpretation": "deletion, move, or lost visibility is unknown",
            },
            "fixture_data": True,
            "object_id": 777,
            "object_kind": "project",
            "prior_source_path": "example-group/retired-project",
            "quarantined_at": FIXED_TIME,
            "reason": "missing_from_scope",
        },
    )
    _write_text(
        destination,
        "stale/components/project/501/wiki.fixture/home.md",
        "# Retained old wiki generation\n",
    )
    _write_json(
        destination,
        "stale/components/project/501/record-wiki.fixture.json",
        {
            "component": "wiki",
            "fixture_data": True,
            "object_id": 501,
            "object_kind": "project",
            "prior_source_path": f"content/projects/{PROJECT_PATH}/wiki",
            "quarantined_at": FIXED_TIME,
            "reason": "configured_exclusion",
        },
    )
    details = [
        {
            "object_kind": "group",
            "object_id": 202,
            "kind": "wiki",
            **group_resource["wiki"],
        },
        *(
            {
                "object_kind": "project",
                "object_id": 501,
                "kind": kind,
                **value,
            }
            for kind, value in sorted(project_resources.items())
        ),
    ]
    _write_json(
        destination,
        "manifest.json",
        {
            "fixture_data": True,
            "identity": {"instance_url": INSTANCE, "root_group_id": 100},
            "run_state": {
                "current": False,
                "latest": {
                    "exit_code": 0,
                    "finished_at": FIXED_TIME,
                    "id": 1,
                    "interrupted": False,
                    "message": None,
                    "outcome": "success",
                    "started_at": FIXED_TIME,
                },
            },
            "drift": {
                "observed_at": FIXED_TIME,
                "absent": [],
                "added": [],
                "path_reused": [],
                "renamed": [],
            },
            "freshness": {
                "last_attempt_at": FIXED_TIME,
                "last_success_at": FIXED_TIME,
            },
            "coverage": {
                "by_status": {"ok": 4},
                "details": details,
                "retained_content": 0,
                "total": 4,
            },
            "limitations": [
                "Synthetic fixture data only; no GitLab version was live-tested."
            ],
        },
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("sample-corpus"),
    )
    generate(parser.parse_args().output)


if __name__ == "__main__":
    main()
